/**
 * Single list of user-visible features. The in-app help links, the guide
 * coverage test, and later the operator handbook all read this array.
 * The first entry that matches a URL wins the "?" link when scores tie,
 * so the main section of a shared route is listed before the extras.
 */
export type FeatureEntry = {
  key: string;
  nameVi: string;
  areaVi: string;
  summaryVi: string;
  webRoutes: string[];
  docPage: string;
  docAnchor: string;
  sinceTask: string;
  settingsKeys?: string[];
};

