export type GuidePageId = (typeof GUIDE_PAGES)[number];

export function isGuidePage(page: string): page is GuidePageId {
  return (GUIDE_PAGES as readonly string[]).includes(page);
}

export function helpPageId(docPage: string): string {
  const base = docPage.split(/[/\\]/).pop() ?? "";
  return base.replace(/\.md$/i, "");
}

export function helpHref(feature: FeatureEntry): string {
  return `/help/${helpPageId(feature.docPage)}#${feature.docAnchor}`;
}

function routeScore(pattern: string, pathname: string): number | null {
  if (pattern === "/") return pathname === "/" ? 100 : null;
  const expected = pattern.split("/").filter(Boolean);
  const actual = pathname.split("/").filter(Boolean);
  if (expected.length !== actual.length) return null;
  let score = 0;
  for (let index = 0; index < expected.length; index += 1) {
    const part = expected[index];
    if (part.startsWith(":")) score += 1;
    else if (part === actual[index]) score += 10;
    else return null;
  }
  return score;
}

/** Best feature for the current URL. A longer literal match beats a param match. */
export function featureForPathname(pathname: string): FeatureEntry | undefined {
  const path = pathname.length > 1 && pathname.endsWith("/") ? pathname.slice(0, -1) : pathname;
  let best: { feature: FeatureEntry; score: number } | undefined;
  for (const feature of featureMap) {
    for (const route of feature.webRoutes) {
      const score = routeScore(route, path);
      if (score === null) continue;
      if (!best || score > best.score) best = { feature, score };
    }
  }
  return best?.feature;
}

